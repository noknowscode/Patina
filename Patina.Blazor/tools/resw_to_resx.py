#!/usr/bin/env python3
"""Generates Patina.Blazor.Shared/Resources/Strings.resx and Strings.fr.resx from the Uno app's
Patina/Strings/{en,fr}/Resources.resw, so both UIs read one string table (tools/make_resw.py is its source).

x:Uid keys carry a property suffix ("Settings_Export.Content"). The Blazor side has no x:Uid, so:
  Key.Text / Key.Content / Key.Label  ->  Key
  Key.Header                           ->  Key_Header
  Key.PlaceholderText                  ->  Key_Placeholder
  Key.[using:...]AutomationProperties.Name -> Key_Name
Collisions are reported and fail the run.
"""
import os, re, html, sys
import xml.etree.ElementTree as ET

here = os.path.dirname(os.path.abspath(__file__))
blazor = os.path.join(here, "..")
repo = os.path.join(blazor, "..")
out_dir = os.path.join(blazor, "Patina.Blazor.Shared", "Resources")

HEAD = '''<?xml version="1.0" encoding="utf-8"?>
<root>
  <!-- Generated by tools/resw_to_resx.py from Patina/Strings/*/Resources.resw. Regenerate instead of editing. -->
  <resheader name="resmimetype"><value>text/microsoft-resx</value></resheader>
  <resheader name="version"><value>2.0</value></resheader>
  <resheader name="reader"><value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
  <resheader name="writer"><value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
'''


def normalize(key):
    base, dot, suffix = key.partition(".")
    if not dot:
        return key
    if suffix in ("Text", "Content", "Label"):
        return base
    if suffix == "Header":
        return base + "_Header"
    if suffix == "PlaceholderText":
        return base + "_Placeholder"
    if suffix.endswith("AutomationProperties.Name"):
        return base + "_Name"
    raise SystemExit(f"unhandled x:Uid suffix: {key}")


def load(lang):
    tree = ET.parse(os.path.join(repo, "Patina", "Strings", lang, "Resources.resw"))
    out = {}
    for data in tree.getroot().findall("data"):
        key = normalize(data.get("name"))
        value = data.find("value").text or ""
        if key in out and out[key] != value:
            raise SystemExit(f"collision after normalizing: {key}")
        out[key] = value
    return out


# Strings the Uno XAML hard-codes as AutomationProperties.Name (not x:Uid), so they are not in the .resw table.
EXTRA = {
    "Survey_RemovePhoto_Name": ("Remove photo", "Retirer la photo"),
    "Artwork_CoverPhoto_Name": ("Cover photograph", "Photographie de la fiche"),
    "Map_Name": ("Map of the collection", "Carte de la collection"),
    "Survey_Weather_Name": ("Weather", "Météo"),
    "Survey_FindingType_Name": ("Finding type", "Type de constat"),
    "Settings_Language_Name": ("Language", "Langue"),
    "Settings_ReduceMotion_Name": ("Reduce motion", "Réduire les animations"),
    "Treatment_Status_Name": ("Status", "État"),
    "Common_Back": ("Back", "Retour"),
}

en, fr = load("en"), load("fr")
for key, (e, f) in EXTRA.items():
    en[key], fr[key] = e, f
if set(en) != set(fr):
    raise SystemExit(f"key sets differ: {sorted(set(en) ^ set(fr))}")

os.makedirs(out_dir, exist_ok=True)
for name, table in (("Strings.resx", en), ("Strings.fr.resx", fr)):
    lines = [HEAD]
    for key in sorted(table):
        lines.append(f'  <data name="{html.escape(key)}" xml:space="preserve"><value>{html.escape(table[key], quote=False)}</value></data>\n')
    lines.append("</root>\n")
    with open(os.path.join(out_dir, name), "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(lines))
print(f"wrote {len(en)} strings per language")
