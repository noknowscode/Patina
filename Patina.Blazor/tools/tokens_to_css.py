#!/usr/bin/env python3
"""Generates Patina.Blazor.Shared/wwwroot/css/tokens.css from the Uno app's design source.

Inputs (all already generated or hand-kept for the Uno app, so the two UIs cannot drift):
  ../docs/DESIGN.md                        typography table
  ../Patina/Styles/ColorPaletteOverride.xaml  Material color roles, Light and Dark (from DesignMd2Uno)
  ../Patina/Styles/Tokens.xaml              spacing and radius (from DesignMd2Uno)
  ../Patina/Styles/Condition.xaml           the four grade colors (theme-invariant)
  ../Patina/Styles/Motion.xaml              easings, durations, entrance rise, press scale

Run from anywhere: python tools/tokens_to_css.py
"""
import re, os, sys

here = os.path.dirname(os.path.abspath(__file__))
blazor = os.path.join(here, "..")
repo = os.path.join(blazor, "..")
out_path = os.path.join(blazor, "Patina.Blazor.Shared", "wwwroot", "css", "tokens.css")


def read(path):
    with open(os.path.join(repo, path), encoding="utf-8") as f:
        return f.read()


def kebab(name):
    return re.sub(r"(?<!^)(?=[A-Z0-9])", "-", name).lower().replace("--", "-")


# Colors: <ResourceDictionary x:Key="Light"> ... <Color x:Key="PrimaryColor">#2F6F62</Color>
palette = read("Patina/Styles/ColorPaletteOverride.xaml")
themes = {}
for theme, body in re.findall(r'<ResourceDictionary x:Key="(Light|Dark)">(.*?)</ResourceDictionary>', palette, re.S):
    themes[theme] = [(kebab(k[:-len("Color")]), v) for k, v in re.findall(r'<Color x:Key="(\w+)">(#[0-9A-Fa-f]{6,8})</Color>', body)]

# Spacing and radius: <x:Double x:Key="SpacingXs">4</x:Double>, <x:Double x:Key="RadiusSm">6</x:Double>
tokens = read("Patina/Styles/Tokens.xaml")
spacing = [(kebab(k[len("Spacing"):]), v) for k, v in re.findall(r'<x:Double x:Key="Spacing(\w+)">([\d.]+)</x:Double>', tokens)]
radius = [(kebab(k), v) for k, v in re.findall(r'<x:Double x:Key="Radius(\w+)">([\d.]+)</x:Double>', tokens)]

# Grade colors
condition = read("Patina/Styles/Condition.xaml")
grades = re.findall(r'<Color x:Key="Grade(\d)InvariantColor">(#[0-9A-Fa-f]{6})</Color>', condition)

# Motion
motion = read("Patina/Styles/Motion.xaml")
eases = re.findall(r'<KeySpline x:Key="(\w+)">([\d., ]+)</KeySpline>', motion)
durations = re.findall(r'<x:Double x:Key="Duration(\w+)Ms">(\d+)</x:Double>', motion)
rise = re.search(r'<x:Double x:Key="EntranceRise">([\d.]+)</x:Double>', motion).group(1)
press = re.search(r'<x:Double x:Key="PressScale">([\d.]+)</x:Double>', motion).group(1)

# Typography table in DESIGN.md: | Style | Font | Size | Line height | Weight | Letter spacing |
design = read("docs/DESIGN.md")
type_rows = []
in_table = False
for line in design.splitlines():
    if line.startswith("| Style |"):
        in_table = True
        continue
    if in_table:
        if not line.startswith("|"):
            break
        cells = [c.strip() for c in line.strip("|").split("|")]
        if cells[0].startswith("---"):
            continue
        style, font, size, lh, weight, ls = cells
        type_rows.append((style.lower(), font, size, lh, weight, ls))

fonts = {
    "IBM Plex Sans Condensed": "--font-display",
    "IBM Plex Sans": "--font-body",
    "IBM Plex Mono": "--font-mono",
}


def css_block(pairs, indent="  "):
    return "\n".join(f"{indent}--color-{k}: {v};" for k, v in pairs)


lines = []
lines.append("/* Generated by tools/tokens_to_css.py from docs/DESIGN.md and Patina/Styles/*.xaml. Regenerate instead of editing. */")
lines.append(":root {")
lines.append("  color-scheme: light dark;")
lines.append("  /* Color roles (Light) */")
lines.append(css_block(themes["Light"]))
lines.append("  /* Condition ramp: theme-invariant by design (patches never carry text) */")
for n, v in grades:
    lines.append(f"  --grade-{n}: {v};")
lines.append("  --grade-0: var(--color-outline-variant);")
lines.append("  /* Spacing */")
for k, v in spacing:
    lines.append(f"  --space-{k}: {v}px;")
lines.append("  /* Corner radius */")
for k, v in radius:
    lines.append(f"  --radius-{k}: {v}px;")
lines.append("  /* Typefaces */")
for family, var in fonts.items():
    lines.append(f"  {var}: '{family}', system-ui, sans-serif;" if "Mono" not in family else f"  {var}: '{family}', ui-monospace, monospace;")
lines.append("  /* Type ramp */")
for style, font, size, lh, weight, ls in type_rows:
    var = fonts[font]
    lines.append(f"  --text-{style}: {weight} {size}/{lh} var({var});")
    lines.append(f"  --tracking-{style}: {ls};")
lines.append("  /* Motion (house values) */")
for k, v in eases:
    a, b = v.split(" ")
    x1, y1 = a.split(",")
    x2, y2 = b.split(",")
    lines.append(f"  --{kebab(k)}: cubic-bezier({x1}, {y1}, {x2}, {y2});")
for k, v in durations:
    lines.append(f"  --duration-{k.lower()}: {v}ms;")
lines.append(f"  --entrance-rise: {rise}px;")
lines.append(f"  --press-scale: {press};")
lines.append("  --content-max-width: 760px;")
lines.append("  --list-pane-width: 420px;")
lines.append("}")
lines.append("")
lines.append("/* Dark: an explicit choice, or the system preference when no choice is made */")
lines.append(':root[data-theme="dark"] {')
lines.append(css_block(themes["Dark"]))
lines.append("}")
lines.append("@media (prefers-color-scheme: dark) {")
lines.append('  :root:not([data-theme="light"]) {')
lines.append(css_block(themes["Dark"], indent="    "))
lines.append("  }")
lines.append("}")
lines.append("")
lines.append("/* Reduced motion: the system query, or the in-app toggle */")
lines.append("@media (prefers-reduced-motion: reduce) {")
lines.append("  :root { --duration-fast: 0ms; --duration-normal: 0ms; --duration-slow: 0ms; --entrance-rise: 0px; }")
lines.append("}")
lines.append(':root[data-reduce-motion="true"] { --duration-fast: 0ms; --duration-normal: 0ms; --duration-slow: 0ms; --entrance-rise: 0px; }')
lines.append("")

os.makedirs(os.path.dirname(out_path), exist_ok=True)
with open(out_path, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines))
print(f"wrote {os.path.relpath(out_path, blazor)}: {len(themes['Light'])} color roles x2, {len(spacing)} spacing, {len(radius)} radius, {len(type_rows)} type styles, {len(grades)} grades")
